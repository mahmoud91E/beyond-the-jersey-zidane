import fs from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
process.chdir(fileURLToPath(new URL('../',import.meta.url)));
const component=fs.readFileSync('components/experience.tsx','utf8');
const content=fs.readFileSync('lib/content.ts','utf8');
const css=fs.readFileSync('app/globals.css','utf8');
const page=fs.readFileSync('app/page.tsx','utf8');
const required=['Hero','QuickCaseStudy','AudienceObjective','ConsumerInsight','MarketObservation','Opportunity','Timeline','TimelineChapter','CampaignSystem','SocialSystem','ScanTheMoment','Measurement','Reflection','AboutContact','SourcesCredits'];
for(const name of required)assert(component.includes(`export function ${name}(`),`Missing ${name}`);
for(const name of required.filter(x=>x!=='TimelineChapter'))assert(page.includes(`<${name}/>`),`Missing page section ${name}`);
for(const text of ['His growing stature turns the number 10 shirt into a recognizable symbol of this period in French football.','The shirt now carries comparison as much as memory.'])assert(content.includes(text),'Approved refinement missing');
assert(!content.includes('His growing stature connects sporting achievement'));
assert(component.includes('Measurement framework — no campaign data collected yet.'));
assert(css.includes('prefers-reduced-motion:reduce'));
assert(!/<img\b|<video\b|<iframe\b/.test(component),'Unexpected media embed');
for(const asset of ['ZIDANE_1998_FINAL','FRANCE_2000_MATCH','FRANCE_2002','ZIDANE_2006_BRAZIL','FRANCE_1998_SHIRT_DETAIL','FRANCE_2006_WHITE_SHIRT'])assert((content+component).includes(asset),`Missing ${asset}`);
JSON.parse(fs.readFileSync('package.json','utf8'));
JSON.parse(fs.readFileSync('tsconfig.json','utf8'));
console.log('Source checks passed: 15 content components, 14 page sections, approved refinements, required placeholders, reduced-motion rules, no raw image/video/iframe embeds, valid JSON.');
console.log('These checks do not establish compilation, browser rendering, accessibility compliance or runtime behavior.');
